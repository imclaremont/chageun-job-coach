// 근로자의 말에서 다쳤거나 아프다는 표현 찾기, 놓치는 것보다 잘못 부르는 편이 안전하므로 넓게 판별
const INJURY_PATTERNS = [
  /(?<!안\s?)다(쳤|쳐|친)/,
  /(?<!안\s?)아(파(?!트)|프(?!리카)|픕|팠)/,
  // '커피가'처럼 다른 낱말 속의 '피' 제외
  /(^|[\s,.!?])피(가|를)?\s*(나|났|흘|흐르|묻)/,
  /데[었였]|뎄|화상/,
  /베[었였]|벴/,
  /찔(렸|려)/,
  /넘어(졌|져)|미끄러(졌|져)/,
  /부딪(혔|쳤|혀|쳐)/,
  /삐(었|끗)/,
  /어지(러|럽)/,
  /쓰러(졌|져|질)/,
  /숨(이|을)?\s*(안|못|막|차)/,
];

export function mentionsInjury(text: string): boolean {
  return INJURY_PATTERNS.some((pattern) => pattern.test(text));
}
